// Generate the Risk 42 world-map asset for the TV second screen from the
// source map (docs/risk/risk-territory-board.svg). OUTPUT IS GENERATED —
// edit this regenerator, never the output (house rule).
//
// Emits:
//   src/lib/assets/risk-world-map.svg      — cleaned <g> fragment: all country
//       outlines; the 40 Risk territories keep id=<slug> and get neutral
//       presentation fills (runtime overrides fill per owner). Filters and
//       non-map layers (flightpaths, tints, tekst) are stripped.
//   src/lib/game/risk-map-anchors.ts      — territory name → label anchor in
//       the fragment's viewBox space (post group-translate), + 2-line wraps.
//
// Run: node docs/risk/generate-world-map-asset.cjs
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'risk-territory-board.svg');
const OUT_SVG = path.join(__dirname, '../../src/lib/assets/risk-world-map.svg');
const OUT_TS = path.join(__dirname, '../../src/lib/game/risk-map-anchors.ts');

// wedge-ring → territory (mirrors risk-engine.ts BOARD; single source there)
const BOARD = {
  '20i': 'Northern Europe', '20o': 'Scandinavia',
  '1i': 'Ukraine', '1o': 'Siberia',
  '18i': 'Ural', '18o': 'Yakutsk',
  '4i': 'Afghanistan', '4o': 'Irkutsk',
  '13i': 'Mongolia', '13o': 'Kamchatka',
  '6i': 'Siam', '6o': 'China',
  '10i': 'India', '10o': 'New Guinea',
  '15i': 'Indonesia', '15o': 'Eastern Australia',
  '2i': 'Middle East', '2o': 'Western Australia',
  '17i': 'Congo', '17o': 'East Africa',
  '3i': 'Egypt', '3o': 'South Africa',
  '19i': 'North Africa', '19o': 'Argentina',
  '7i': 'Southern Europe', '7o': 'Brazil',
  '16i': 'Venezuela', '16o': 'Peru',
  '8i': 'Western Europe', '8o': 'Central America',
  '11i': 'Eastern United States', '11o': 'Western United States',
  '14i': 'Ontario', '14o': 'Alberta',
  '9i': 'Quebec', '9o': 'Alaska',
  '12i': 'Great Britain', '12o': 'Northwest Territory',
  '5i': 'Greenland', '5o': 'Iceland',
};
const TERRITORIES = Object.values(BOARD);
const slug = (t) => t.toLowerCase().replace(/ /g, '_');
// source-map quirks
const ID_FIXES = { yakutsk: 'yakursk' };

const svg = fs.readFileSync(SRC, 'utf8');

// ---- extract the countries layer's inner content ----
function layerSpan(label) {
  const i = svg.indexOf(`inkscape:label="${label}"`);
  if (i < 0) throw new Error('no layer ' + label);
  const open = svg.indexOf('>', i);
  let depth = 1, j = open + 1;
  while (depth > 0 && j < svg.length) {
    const openM = svg.slice(j).match(/<g[\s>]/);
    const closeM = svg.slice(j).match(/<\/g>/);
    if (closeM && (!openM || closeM.index < openM.index)) { depth--; j += closeM.index + 4; }
    else if (openM) { depth++; j += openM.index + 2; }
    else throw new Error('unbalanced');
  }
  return [open + 1, j - 4]; // inner content of the <g>
}
const [cStart, cEnd] = layerSpan('countries');
const countriesInner = svg.slice(cStart, cEnd);

// ---- clean + classify country paths ----
const riskSlugs = new Set(TERRITORIES.map((t) => slug(t)));
const paths = [...countriesInner.matchAll(/<path\b[^>]*>/g)].map((m) => m[0]);
const out = [];
const seen = new Set();
const attr = (tag, name) => (tag.match(new RegExp('\\s' + name + '="([^"]*)"')) || [])[1];
for (const p of paths) {
  let id = attr(p, 'id');
  if (!id) continue;
  for (const [want, have] of Object.entries(ID_FIXES)) if (id === have) id = want; // normalize quirks
  const isRisk = riskSlugs.has(id);
  if (id === 'madagascar-grayed' || id === 'japan-grayed') continue; // cut territories
  const d = attr(p, 'd');
  const transform = attr(p, 'transform');
  out.push(
    `<path id="${id}"${isRisk ? ' data-territory="1"' : ''}${transform ? ` transform="${transform}"` : ''} d="${d}" />`,
  );
  if (isRisk) seen.add(id);
}
const missing = TERRITORIES.map(slug).filter((s) => !seen.has(s));
if (missing.length) throw new Error('missing risk country paths: ' + missing.join(', '));

// viewBox of the source map (shared by all layers post-translate)
const vb = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
const [W, H] = [+vb[1], +vb[2]];
const TX = -167.99651, TY = -118.55507; // shared group translate (all layers)

const fragment = `<!-- GENERATED by docs/risk/generate-world-map-asset.cjs — do not edit -->
<!-- World map (docs/risk/risk-territory-board.svg), cleaned: countries only;
     the 40 Risk territories carry id=<slug> and a data-territory marker and are
     filled neutrally here — the app overrides fill per owning player.
     Coordinate space: viewBox 0 0 ${W} ${H} (the shared layer translate is applied). -->
<g id="risk-world-map">
<rect x="0" y="0" width="${W}" height="${H}" fill="#0a0f1a" />
<g transform="translate(${TX}, ${TY})">
${out.join('\n')}
</g>
</g>`;

// default presentation: risk territories mid-neutral, others dark
fs.mkdirSync(path.dirname(OUT_SVG), { recursive: true });
fs.writeFileSync(
  OUT_SVG,
  fragment
    .replace(/(<path id="[^"]+" data-territory="1"[^>]*?) ?\/>/g, '$1 fill="#232a36" stroke="#6b7a90" stroke-width="1.1" />')
    .replace(/(<path id="[^"]+"(?![^>]*data-territory)[^>]*?) ?\/>/g, '$1 fill="#141b28" stroke="#2c3644" stroke-width="0.9" />'),
);

// ---- label anchors from the "territory labels" layer ----
const [tStart, tEnd] = layerSpan('territory labels');
const labelsInner = svg.slice(tStart, tEnd);
// TX/TY defined at the top with the viewBox extraction
const anchors = {};
for (const m of labelsInner.matchAll(
  /<text><tspan x="([\d.-]+)" y="([\d.-]+)"[^>]*>([^<]+)<\/tspan>(?:<tspan[^>]*>([^<]*)<\/tspan>)?<\/text>/g,
)) {
  const lines = [m[3], m[4]].filter(Boolean);
  const name = TERRITORIES.includes(lines.join(' ')) ? lines.join(' ') : null;
  if (!name) continue;
  anchors[name] = { x: +( (+m[1] + TX).toFixed(1) ), y: +( (+m[2] + TY).toFixed(1) ), lines };
}
const missingAnchors = TERRITORIES.filter((t) => !anchors[t]);
if (missingAnchors.length) throw new Error('missing anchors: ' + missingAnchors.join(', '));

fs.writeFileSync(
  OUT_TS,
  `// GENERATED by docs/risk/generate-world-map-asset.cjs — do not edit
// Territory → label anchor in the risk-world-map.svg coordinate space
// (viewBox 0 0 ${W} ${H}). Shared by the TV map; regen via the script.
export interface MapAnchor { x: number; y: number; lines: string[] }
export const MAP_VIEWBOX = { w: ${W}, h: ${H} } as const;
export const MAP_ANCHORS: Record<string, MapAnchor> = ${JSON.stringify(anchors, null, 1)};
`,
);
console.log(`ok: ${out.length} country paths (${seen.size} risk), ${Object.keys(anchors).length} anchors -> ${path.relative(process.cwd(), OUT_SVG)}, ${path.relative(process.cwd(), OUT_TS)}`);
